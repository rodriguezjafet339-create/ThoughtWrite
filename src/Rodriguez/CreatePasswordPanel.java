    private void createButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_createButtonActionPerformed
        char[] pw = passwordField.getPassword();
        char[] confirm = confirmPasswordField.getPassword();
        try {
            if (pw.length == 0) {
                JOptionPane.showMessageDialog(this, "Password can't be empty.",
                        "Empty password", JOptionPane.WARNING_MESSAGE);
                passwordField.requestFocusInWindow();
                return;
            }
            if (!Arrays.equals(pw, confirm)) {
                JOptionPane.showMessageDialog(this, "The two passwords don't match.",
                        "Passwords don't match", JOptionPane.WARNING_MESSAGE);
                confirmPasswordField.setText("");
                confirmPasswordField.requestFocusInWindow();
                return;
            }
            onCreate.accept(pw);
            clear();
        } finally {
            Arrays.fill(pw, '\0');
            Arrays.fill(confirm, '\0');
        }
    }//GEN-LAST:event_createButtonActionPerformed

