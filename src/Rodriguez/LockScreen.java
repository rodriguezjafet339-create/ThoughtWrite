    public LockScreen(AuthService auth, Runnable onUnlocked) {
        this();
        this.auth = auth;
        this.onUnlocked = onUnlocked;
    }

    /** Call every time this screen is about to be shown. Resets the field and checks for a cooldown. */
    public void refresh() {
        passwordField.setText("");
        warningText.setText(" ");
        try {
            if (auth != null && auth.isLockedOut()) {
                startCooldownView();
            } else {
                countdown.stop();
                setInputEnabled(true);
                SwingUtilities.invokeLater(passwordField::requestFocusInWindow);
            }
        } catch (Exception ex) {
            showError(ex);
        }
    }

    // ---------------------------------------------------------------- unlocking

    private void attemptUnlock() {
        if (auth == null) {
            return;
        }
        char[] pw = passwordField.getPassword();
        try {
            if (pw.length == 0) {
                warningText.setText("Enter your password.");
                return;
            }
            boolean ok = auth.tryUnlock(pw);
            passwordField.setText("");
            if (ok) {
                countdown.stop();
                onUnlocked.run();
                return;
            }
            if (auth.isLockedOut()) {
                startCooldownView();           // that was the 3rd wrong try
            } else {
                int left = auth.attemptsLeft();
                warningText.setText("Wrong password. " + left + (left == 1 ? " try left." : " tries left."));
            }
        } catch (Exception ex) {
            showError(ex);
        } finally {
            Arrays.fill(pw, '\0');
        }
    }

    // ----------------------------------------------------------------- cooldown

    private void startCooldownView() {
        setInputEnabled(false);
        showCountdownText();
        countdown.start();
    }

    private void showCountdownText() {
        long s = auth.secondsLeft();
        warningText.setText(String.format("Locked. Try again in %d:%02d", s / 60, s % 60));
    }

    private void tick() {
        try {
            if (auth.isLockedOut()) {
                showCountdownText();
            } else {                           // cooldown over: 3 fresh tries
                countdown.stop();
                setInputEnabled(true);
                warningText.setText(" ");
                passwordField.requestFocusInWindow();
            }
        } catch (Exception ex) {
            countdown.stop();
            showError(ex);
        }
    }

    private void setInputEnabled(boolean enabled) {
        passwordField.setEnabled(enabled);
        enterButton.setEnabled(enabled);
    }

    private void showError(Exception ex) {
        JOptionPane.showMessageDialog(this, "Something went wrong: " + ex.getMessage(),
                "ThoughtWrite", JOptionPane.ERROR_MESSAGE);
    }

